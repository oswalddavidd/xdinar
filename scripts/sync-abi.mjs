#!/usr/bin/env node
// Regenerates lib/abi/*.ts from the Hardhat build artifacts so the dApp never drifts
// from the deployed contracts. Run after every `npx hardhat compile` in the contracts repo:
//
//   npm run sync-abi
//   XDINAR_CONTRACTS_DIR=/path/to/contracts npm run sync-abi
//
// The ABI is copied verbatim (including internalType) and exported `as const` for wagmi/viem typing.

import { readFileSync, writeFileSync, mkdirSync, statSync } from 'node:fs'
import { resolve, dirname, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const contractsDir = resolve(root, process.env.XDINAR_CONTRACTS_DIR ?? '../../xdinar')
const outDir = resolve(root, 'lib/abi')

const CONTRACTS = [
  { name: 'xDinarStaking', exportName: 'STAKING_ABI' },
  { name: 'xDinarToken', exportName: 'TOKEN_ABI' },
]

mkdirSync(outDir, { recursive: true })

for (const { name, exportName } of CONTRACTS) {
  const artifactPath = resolve(contractsDir, `artifacts/contracts/${name}.sol/${name}.json`)
  const sourcePath = resolve(contractsDir, `contracts/${name}.sol`)
  const artifact = JSON.parse(readFileSync(artifactPath, 'utf8'))

  if (statSync(sourcePath).mtimeMs > statSync(artifactPath).mtimeMs) {
    console.warn(`⚠ ${name}.sol is newer than its artifact. Run \`npx hardhat compile\` first.`)
  }

  const out =
    `// AUTO-GENERATED by scripts/sync-abi.mjs from ${relative(root, artifactPath)}\n` +
    `// Do not edit by hand. Re-run \`npm run sync-abi\` after recompiling the contracts.\n\n` +
    `export const ${exportName} = ${JSON.stringify(artifact.abi, null, 2)} as const\n`

  writeFileSync(resolve(outDir, `${name}.ts`), out)
  console.log(`✓ lib/abi/${name}.ts (${artifact.abi.length} entries)`)
}
